"""Fixed, documented configuration for model training and evaluation.

Every random operation uses ``RANDOM_STATE`` (shared with the Phase 3 split), so a
training run on the same data and library versions reproduces the same results.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path

from analytics.preprocessing import RANDOM_STATE

#: Folds for the outer (performance) and inner (tuning) cross-validation.
#: Five folds keep each validation fold large enough to be informative (≈ 63 students
#: in Mathematics, ≈ 104 in Portuguese; ≈ 21 and ≈ 16 at-risk students respectively)
#: while training on 80% of the training set. Ten folds would halve the validation
#: folds and make per-fold F1 and ROC-AUC very noisy for the minority class.
CV_FOLDS = 5
#: Decision rule of every classifier's ``predict``: at risk when P(at risk) > 0.5 (the more
#: probable class), or when the SVM decision score is > 0. Not tuned.
DECISION_THRESHOLD = 0.5
#: Default location of trained artefacts (git-ignored; regenerated by the CLI).
DEFAULT_MODELS_DIR = Path(__file__).resolve().parents[3] / "models"


class Task(StrEnum):
    REGRESSION = "regression"
    CLASSIFICATION = "classification"


class SearchMode(StrEnum):
    #: The documented grid for every model.
    FULL = "full"
    #: First value of each grid entry and small forests. For fast automated tests only.
    MINIMAL = "minimal"


@dataclass(frozen=True)
class TrainingConfig:
    random_state: int = RANDOM_STATE
    cv_folds: int = CV_FOLDS
    search: SearchMode = SearchMode.FULL
    #: Parallel workers for grid search. Results do not depend on this value.
    n_jobs: int = -1
    #: Restrict training to these model keys (None = every registered model).
    models: tuple[str, ...] | None = field(default=None)
