"""Generate docs/STATISTICAL_FINDINGS.md from the official data.

Usage (from backend/, after downloading the dataset):

    python -m analytics.statistics.findings

Every number in the document is computed here; nothing is typed by hand. A test
regenerates the document and fails if the committed copy is stale.
"""

from __future__ import annotations

from pathlib import Path

from analytics.data import Cohort, load_cohort
from analytics.data.download import DEFAULT_RAW_DIR
from analytics.preprocessing import prepare_cohort
from analytics.statistics.association import associations
from analytics.statistics.correlation import correlations
from analytics.statistics.distributions import distributions
from analytics.statistics.outliers import outliers
from analytics.statistics.research import research_questions

OUTPUT = Path(__file__).resolve().parents[3] / "docs" / "STATISTICAL_FINDINGS.md"


def _p(p: float | None) -> str:
    return "—" if p is None else ("< 0.001" if p < 0.001 else f"{p:.3f}")


def _cohort_section(cohort: Cohort, raw_dir: Path) -> list[str]:
    data = prepare_cohort(load_cohort(raw_dir, cohort)).analytical
    name = "Mathematics" if cohort is Cohort.MATH else "Portuguese language"
    dist = distributions(data, str(cohort))
    g3 = next(g for g in dist.grades if g.variable == "G3")
    s = g3.summary
    rq = research_questions(data, str(cohort))
    cor = correlations(data, str(cohort))
    assoc = associations(data, str(cohort))
    out = outliers(data, str(cohort))
    r = dist.risk

    lines = [
        f"## {name} (n = {len(data)})",
        "",
        "### Final grade (G3)",
        "",
        f"- Mean {s.mean:.2f} (95% CI {s.mean_ci.low:.2f}–{s.mean_ci.high:.2f}), "
        f"median {s.median:g}, "
        f"SD {s.std:.2f}, IQR {s.q1:g}–{s.q3:g}, range {s.minimum:g}–{s.maximum:g}.",
        f"- Shape: {g3.shape.description} Skewness {g3.shape.skewness:.2f}, excess kurtosis "
        f"{g3.shape.kurtosis:.2f}.",
        f"- Academic risk (G3 < {r.threshold}): {r.at_risk} of {r.n} = {100 * r.proportion:.1f}% "
        f"(95% Wilson CI {100 * r.proportion_ci.low:.1f}–{100 * r.proportion_ci.high:.1f}%).",
    ]
    lines += [f"- {o}" for o in dist.observations]
    lines += [
        "",
        "### Research questions",
        "",
        "| RQ | Evidence | Test | Adjusted p | Effect | Result |",
        "| -- | -------- | ---- | ---------- | ------ | ------ |",
    ]
    for q in rq.items:
        effect = (
            f"{q.effect.name} = {q.effect.value:.2f} ({q.effect.magnitude})"
            if q.effect and q.effect.value is not None
            else "—"
        )
        verdict = "significant" if q.significant else "not significant"
        lines.append(
            f"| {q.key} | {q.evidence} | {q.test} | {_p(q.p_adjusted)} | {effect} | {verdict} |"
        )
    lines += ["", "Findings:", ""]
    for q in rq.items:
        lines.append(f"- **{q.key}.** {q.finding}")
        if q.sensitivity:
            lines.append(f"  *Sensitivity:* {q.sensitivity}")
    lines += [
        "",
        "### Key correlations with G3",
        "",
        "| Variable | Method | r | 95% CI | n | Holm p | Without G3 = 0 |",
        "| -------- | ------ | - | ------ | - | ------ | -------------- |",
    ]
    for c, sens in zip(cor.key_pairs, cor.sensitivity_key_pairs, strict=True):
        lines.append(
            f"| {c.x_label} | {c.method} | {c.r:.2f} | {c.r_ci.low:.2f} to {c.r_ci.high:.2f} | "
            f"{c.n} | {_p(c.p_adjusted)} | {sens.r:.2f} (n = {sens.n}) |"
        )
    lines += [
        "",
        "### Associations with academic risk (exploratory, Benjamini–Hochberg)",
        "",
        "| Variable | Test | Cramér's V | BH p | Highest-risk group |",
        "| -------- | ---- | ---------- | ---- | ------------------ |",
    ]
    for a in sorted(assoc.items, key=lambda a: -(a.cramers_v or 0)):
        top = max(a.rows, key=lambda row: row.risk_percent)
        lines.append(
            f"| {a.label} | {a.test} | {a.cramers_v:.2f} ({a.magnitude}) | {_p(a.p_adjusted)} | "
            f"{top.label}: {top.risk_percent:.1f}% at risk (n = {top.n}) |"
        )
    lines += [
        "",
        "### Outlier screening (flagged, not removed)",
        "",
        "| Variable | Fences | Flagged | Share | abs(z) > 3 |",
        "| -------- | ------ | ------- | ----- | ------ |",
    ]
    for o in out.items:
        lines.append(
            f"| {o.label} | {o.lower_fence:g} to {o.upper_fence:g} | {o.count} | "
            f"{100 * o.proportion:.1f}% | {o.z_count} |"
        )
    return lines + [""]


def render(raw_dir: Path = DEFAULT_RAW_DIR) -> str:
    lines = [
        "# Statistical Findings",
        "",
        "<!-- Generated by backend/analytics/statistics/findings.py from the official UCI files.",
        (
            "Do not edit by hand. Regenerate: cd backend && python -m "
            "analytics.statistics.findings -->"
        ),
        "",
        "Results of the Phase 4 analysis on the official UCI Student Performance data. All",
        "students are included, including those with G3 = 0. Methods, assumptions and the",
        (
            "correction strategy are described in "
            "[METHODOLOGY.md](METHODOLOGY.md#5-statistical-analysis-phase-4)."
        ),
        "",
        "**How to read this document.**",
        "",
        "- Every result is a statistical *association* in observational data from two",
        "  Portuguese schools. None is evidence of cause.",
        "- RQ1–RQ6b are pre-specified confirmatory tests, Holm-adjusted within each cohort.",
        "  Everything else is exploratory.",
        "- Significance does not mean importance: read the effect sizes.",
        "- Confidence intervals are 95% and not adjusted for multiplicity.",
        "",
    ]
    for cohort in Cohort:
        lines += _cohort_section(cohort, raw_dir)
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")
